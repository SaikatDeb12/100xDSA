bool isPrime(int n) {
    if (n <= 1)
        return false;
    if (n <= 3)
        return true;
    if (n % 2 == 0 || n % 3 == 0)
        return false;
    for (int i = 5; i * i <= n; i += 6)
        if (n % i == 0 || n % (i + 2) == 0)
            return false;
    return true;
}
void solve() {
    int n, k;
    cin >> n >> k;
    vector<int> a(n);
    for (auto &i : a)
        cin >> i;

    int cnt = 0;
    for (int i = 0; i < k; i++) {
        cnt += isPrime(a[i]);
    }

    int mx = cnt;
    int i = 0, j = k;
    int l = 0, r = k;
    while (r < n) {
        if (isPrime(a[l]))
            cnt--;
        if (isPrime(a[r]))
            cnt++;
        l++;
        r++;
        if (cnt > mx) {
            mx = cnt;
            i = l;
            j = r;
        }
    }
    for (int x = i; x < j; x++) {
        cout << a[x] << " ";
    }
    cout << "\n";
}

